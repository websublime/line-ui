#!/usr/bin/env bun

/**
 * scripts/generate-palettes.mjs — line-colors palette generator.
 *
 * Bun script (Node-compatible APIs + bun's native TS import) invoked per
 * docs/specs/00-spec-design-system.md §6.C.3 (C3):
 *
 *   bun run scripts/generate-palettes.mjs --output packages/line-colors/src/
 *
 * Emits, under the --output directory:
 *   - {H}.css for each of the 31 HUES — base + alpha sRGB scales via
 *     light-dark(), a static per-hue contrast token, and a wide-gamut P3
 *     override block (@supports + @media (color-gamut: p3)).
 *   - special.css — the four special scales (blackA/whiteA sRGB outside
 *     light-dark(); blackP3A/whiteP3A inside the @supports block).
 *   - index.css — the @import barrel of all 31 hue files + special.css.
 *
 * Generated CSS is COMMITTED (regeneration policy D2, §6.C.3): this script runs
 * only when @radix-ui/colors is bumped or PER_HUE_CONTRAST is intentionally
 * edited. A freshness guard (scripts/verify-palettes-fresh.mjs, C4) diffs the
 * committed output against a fresh run in CI.
 *
 * Radix object-vs-step-key naming (§6.C.3, AM-011): in @radix-ui/colors the
 * scale OBJECT name carries the variant (Dark, P3, A, and combinations) but the
 * step KEYS do not repeat that suffix. Base scales are keyed `{H}{n}`; alpha
 * scales are keyed `{H}A{n}` — regardless of the object's own suffix. This
 * script indexes base objects with `{H}{n}` and alpha objects with `{H}A{n}`.
 *
 * Biome-conformant output: P3 alpha declarations (long
 * `light-dark(color(display-p3 …), color(display-p3 …))` lines) overflow Biome's
 * 120-char CSS lineWidth and must be wrapped. Rather than hand-roll Biome's
 * wrapping rules, the generator delegates final formatting to `biome format
 * --write` over the emitted files as its last step. Biome formatting is
 * deterministic, so re-running the generator reproduces byte-identical files —
 * the C4 freshness guard (scripts/verify-palettes-fresh.mjs) stays green.
 */

import { spawnSync } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import * as radixColors from '@radix-ui/colors';
import { PER_HUE_CONTRAST } from '../packages/line-schemas/src/contrast-table.ts';
import { HUES } from '../packages/line-schemas/src/hues.ts';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, '..');

const STEPS = Array.from({ length: 12 }, (_, i) => i + 1);

const GENERATED_HEADER = '/* AUTO-GENERATED by scripts/generate-palettes.mjs — do not edit by hand */';

/**
 * Parse --output <dir> (default: packages/line-colors/src/), per §6.C.3.
 * @param {string[]} argv
 * @returns {string}
 */
function parseOutputDir(argv) {
  const flagIndex = argv.indexOf('--output');
  if (flagIndex !== -1) {
    const value = argv[flagIndex + 1];
    if (!value) {
      throw new Error('--output requires a directory argument');
    }
    return resolve(REPO_ROOT, value);
  }
  const inline = argv.find((arg) => arg.startsWith('--output='));
  if (inline) {
    return resolve(REPO_ROOT, inline.slice('--output='.length));
  }
  return resolve(REPO_ROOT, 'packages/line-colors/src');
}

/**
 * Resolve a Radix scale object by name, throwing on a missing object so the
 * generator fails loudly rather than emitting silently-broken CSS.
 * @param {string} name
 * @returns {Record<string, string>}
 */
function scale(name) {
  // Radix scales are looked up by a computed object name (e.g. `amberDarkP3A`);
  // dynamic namespace access is intrinsic to a code generator and unavoidable here.
  // biome-ignore lint/performance/noDynamicNamespaceImportAccess: generator resolves scales by computed name
  const obj = radixColors[name];
  if (!obj) {
    throw new Error(`@radix-ui/colors export "${name}" not found`);
  }
  return obj;
}

/**
 * Read a step value from a Radix scale, throwing if the key is absent. Guards
 * against the object-vs-step-key drift documented in §6.C.3.
 * @param {Record<string, string>} obj
 * @param {string} objName
 * @param {string} key
 * @returns {string}
 */
function step(obj, objName, key) {
  const value = obj[key];
  if (value === undefined) {
    throw new Error(`@radix-ui/colors ${objName}.${key} is undefined`);
  }
  return value;
}

/**
 * Build one hue's CSS file content.
 * @param {string} hue
 * @returns {string}
 */
function renderHue(hue) {
  // sRGB scales.
  const base = scale(hue); // {H}{n}
  const baseDark = scale(`${hue}Dark`); // {H}{n}
  const alpha = scale(`${hue}A`); // {H}A{n}
  const alphaDark = scale(`${hue}DarkA`); // {H}A{n}
  // Wide-gamut P3 scales.
  const baseP3 = scale(`${hue}P3`); // {H}{n}
  const baseDarkP3 = scale(`${hue}DarkP3`); // {H}{n}
  const alphaP3 = scale(`${hue}P3A`); // {H}A{n}
  const alphaDarkP3 = scale(`${hue}DarkP3A`); // {H}A{n}

  const baseKey = (n) => `${hue}${n}`;
  const alphaKey = (n) => `${hue}A${n}`;

  const lines = [];
  lines.push(GENERATED_HEADER);
  lines.push(':where(html) {');

  lines.push('  /* Base steps (sRGB) — light-dark() over light + dark base scales */');
  for (const n of STEPS) {
    const k = baseKey(n);
    lines.push(`  --line-${hue}-${n}: light-dark(${step(base, hue, k)}, ${step(baseDark, `${hue}Dark`, k)});`);
  }

  lines.push('');
  lines.push('  /* Alpha steps (sRGB) — light-dark() over alpha light + alpha dark scales */');
  for (const n of STEPS) {
    const k = alphaKey(n);
    lines.push(
      `  --line-${hue}-a${n}: light-dark(${step(alpha, `${hue}A`, k)}, ${step(alphaDark, `${hue}DarkA`, k)});`,
    );
  }

  lines.push('');
  lines.push('  /* Contrast (static single value per hue, NOT light-dark()) */');
  lines.push(`  --line-${hue}-contrast: ${PER_HUE_CONTRAST[hue]};`);
  lines.push('}');

  lines.push('');
  lines.push('/* Wide-gamut P3 override — same token names, automatic upgrade */');
  lines.push('@supports (color: color(display-p3 1 1 1)) {');
  lines.push('  @media (color-gamut: p3) {');
  lines.push('    :where(html) {');
  for (const n of STEPS) {
    const k = baseKey(n);
    lines.push(
      `      --line-${hue}-${n}: light-dark(${step(baseP3, `${hue}P3`, k)}, ${step(baseDarkP3, `${hue}DarkP3`, k)});`,
    );
  }
  lines.push('');
  for (const n of STEPS) {
    const k = alphaKey(n);
    lines.push(
      `      --line-${hue}-a${n}: light-dark(${step(alphaP3, `${hue}P3A`, k)}, ${step(alphaDarkP3, `${hue}DarkP3A`, k)});`,
    );
  }
  lines.push('    }');
  lines.push('  }');
  lines.push('}');

  return `${lines.join('\n')}\n`;
}

/**
 * Build special.css content (blackA / whiteA sRGB + blackP3A / whiteP3A P3).
 * @returns {string}
 */
function renderSpecial() {
  const blackA = scale('blackA'); // blackA{n}
  const whiteA = scale('whiteA'); // whiteA{n}
  const blackP3A = scale('blackP3A'); // blackA{n}
  const whiteP3A = scale('whiteP3A'); // whiteA{n}

  const lines = [];
  lines.push(GENERATED_HEADER);
  lines.push(':where(html) {');
  lines.push('  /* Alpha-on-black (sRGB) — identical in light + dark, no light-dark() */');
  for (const n of STEPS) {
    lines.push(`  --line-black-a${n}: ${step(blackA, 'blackA', `blackA${n}`)};`);
  }
  lines.push('');
  lines.push('  /* Alpha-on-white (sRGB) — identical in light + dark, no light-dark() */');
  for (const n of STEPS) {
    lines.push(`  --line-white-a${n}: ${step(whiteA, 'whiteA', `whiteA${n}`)};`);
  }
  lines.push('}');

  lines.push('');
  lines.push('/* Wide-gamut P3 override — same token names, automatic upgrade */');
  lines.push('@supports (color: color(display-p3 1 1 1)) {');
  lines.push('  @media (color-gamut: p3) {');
  lines.push('    :where(html) {');
  for (const n of STEPS) {
    lines.push(`      --line-black-a${n}: ${step(blackP3A, 'blackP3A', `blackA${n}`)};`);
  }
  lines.push('');
  for (const n of STEPS) {
    lines.push(`      --line-white-a${n}: ${step(whiteP3A, 'whiteP3A', `whiteA${n}`)};`);
  }
  lines.push('    }');
  lines.push('  }');
  lines.push('}');

  return `${lines.join('\n')}\n`;
}

/**
 * Build the index.css @import barrel: 31 hue files (HUES order) + special.css.
 * @returns {string}
 */
function renderBarrel() {
  const lines = [];
  lines.push('/* @websublime/line-colors — palette barrel.');
  lines.push(' *');
  lines.push(' * AUTO-GENERATED by scripts/generate-palettes.mjs — do not edit by hand.');
  lines.push(' * @import of all 31 hue scales (HUES order) + the special alpha scales.');
  lines.push(' * postcss-import inlines these into a single flat dist/index.css at build time.');
  lines.push(' */');
  lines.push('');
  for (const hue of HUES) {
    lines.push(`@import "./${hue}.css";`);
  }
  lines.push('');
  lines.push('/* Special alpha-on-black / alpha-on-white scales. */');
  lines.push('@import "./special.css";');
  return `${lines.join('\n')}\n`;
}

/**
 * Run `biome format --write` over the generated CSS so the committed output
 * matches Biome's formatter (notably wrapping long P3-alpha light-dark() lines
 * that exceed the 120-char CSS lineWidth). Biome formatting is deterministic, so
 * this keeps regeneration byte-stable for the C4 freshness guard. Throws on a
 * non-zero exit so the generator fails loudly rather than committing unformatted
 * output.
 * @param {string} outputDir
 */
function formatWithBiome(outputDir) {
  const biomeBin = resolve(REPO_ROOT, 'node_modules/.bin/biome');
  const result = spawnSync(biomeBin, ['format', '--write', outputDir], {
    cwd: REPO_ROOT,
    encoding: 'utf8',
  });
  if (result.error) {
    throw new Error(`biome format failed to run: ${result.error.message}`);
  }
  if (result.status !== 0) {
    throw new Error(`biome format exited with code ${result.status}: ${result.stderr || result.stdout}`);
  }
}

async function main() {
  const outputDir = parseOutputDir(process.argv.slice(2));
  await mkdir(outputDir, { recursive: true });

  let count = 0;
  for (const hue of HUES) {
    await writeFile(resolve(outputDir, `${hue}.css`), renderHue(hue), 'utf8');
    count += 1;
  }
  await writeFile(resolve(outputDir, 'special.css'), renderSpecial(), 'utf8');
  await writeFile(resolve(outputDir, 'index.css'), renderBarrel(), 'utf8');

  formatWithBiome(outputDir);

  process.stdout.write(`generate-palettes: wrote ${count} hue files + special.css + index.css to ${outputDir}\n`);
}

main().catch((error) => {
  process.stderr.write(`generate-palettes: ${error.message}\n`);
  process.exitCode = 1;
});
