#!/usr/bin/env bun

/**
 * scripts/generate-role-maps.mjs — line-themes role-map generator.
 *
 * Bun script (Node-compatible APIs + bun's native TS import) invoked per
 * docs/specs/00-spec-design-system.md §6.C.4 (C6):
 *
 *   bun run scripts/generate-role-maps.mjs --output packages/line-themes/src/
 *
 * Emits, under the --output directory:
 *   - accent/{H}.css for each of the 31 HUES — remaps --line-accent-1..12,
 *     --line-accent-a1..a12, and --line-accent-contrast onto the hue's own
 *     --line-{H}-* palette tokens, scoped to :where([data-accent="{H}"]).
 *   - gray/{G}.css for each of the 6 GRAY_HUES — remaps --line-gray-1..12,
 *     --line-gray-a1..a12, and --line-gray-contrast onto the gray hue's own
 *     --line-{G}-* tokens, scoped to :where([data-gray="{G}"]).
 *
 * The hand-authored files (semantics.css, defaults.css, aliases.css) and the
 * index.css barrel are NOT generated by this script — they are committed by
 * hand per §6.C.4. This script owns only the per-hue accent/ and gray/ remaps.
 *
 * Import discipline (Manifesto Law 10, spec §6.C.10, enforced by
 * scripts/lint-layers.mjs): this generator imports ONLY from line-schemas —
 * HUES and GRAY_HUES. No Radix, no line-colors, no other package.
 *
 * Selector contract (spec §6.C.4, PRD §9.14 T4, §9.7): role-mapping CSS uses
 * ONLY [data-accent="{H}"] and [data-gray="{G}"] selectors, wrapped in :where()
 * for zero specificity. There is NO [data-theme] selector anywhere in the
 * line-themes output.
 *
 * Biome-conformant output: the generator delegates final formatting to `biome
 * format --write` over the emitted files as its last step, exactly as
 * scripts/generate-palettes.mjs does. Biome formatting is deterministic, so
 * re-running the generator reproduces byte-identical files — keeping C9's CSS
 * snapshots deterministic. Throws on a non-zero biome exit so the generator
 * fails loudly rather than committing unformatted output.
 */

import { spawnSync } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { GRAY_HUES, HUES } from '../packages/line-schemas/src/hues.ts';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, '..');

const STEPS = Array.from({ length: 12 }, (_, i) => i + 1);

const GENERATED_HEADER = '/* AUTO-GENERATED by scripts/generate-role-maps.mjs — do not edit by hand */';

/**
 * Parse --output <dir> (default: packages/line-themes/src/), per §6.C.4.
 * @param {string[]} argv
 * @returns {string}
 */
function parseOutputDir(argv) {
  const flagIndex = argv.indexOf('--output');
  if (flagIndex !== -1) {
    const value = argv[flagIndex + 1];
    if (!value) {
      throw new Error('--output requires a directory argument');
    }
    return resolve(REPO_ROOT, value);
  }
  const inline = argv.find((arg) => arg.startsWith('--output='));
  if (inline) {
    return resolve(REPO_ROOT, inline.slice('--output='.length));
  }
  return resolve(REPO_ROOT, 'packages/line-themes/src');
}

/**
 * Build one accent role-map file: remap --line-accent-* onto the hue's tokens,
 * scoped to :where([data-accent="{hue}"]).
 * @param {string} hue
 * @returns {string}
 */
function renderAccent(hue) {
  const lines = [];
  lines.push(GENERATED_HEADER);
  lines.push(`:where([data-accent="${hue}"]) {`);
  for (const n of STEPS) {
    lines.push(`  --line-accent-${n}: var(--line-${hue}-${n});`);
  }
  for (const n of STEPS) {
    lines.push(`  --line-accent-a${n}: var(--line-${hue}-a${n});`);
  }
  lines.push(`  --line-accent-contrast: var(--line-${hue}-contrast);`);
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

/**
 * Build one gray role-map file: remap --line-gray-* onto the gray hue's tokens,
 * scoped to :where([data-gray="{grayHue}"]).
 * @param {string} grayHue
 * @returns {string}
 */
function renderGray(grayHue) {
  const lines = [];
  lines.push(GENERATED_HEADER);
  lines.push(`:where([data-gray="${grayHue}"]) {`);
  for (const n of STEPS) {
    lines.push(`  --line-gray-${n}: var(--line-${grayHue}-${n});`);
  }
  for (const n of STEPS) {
    lines.push(`  --line-gray-a${n}: var(--line-${grayHue}-a${n});`);
  }
  lines.push(`  --line-gray-contrast: var(--line-${grayHue}-contrast);`);
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

/**
 * Run `biome format --write` over the generated CSS so the committed output
 * matches Biome's formatter. Biome formatting is deterministic, so this keeps
 * regeneration byte-stable for downstream CSS snapshots. Throws on a non-zero
 * exit so the generator fails loudly rather than committing unformatted output.
 * @param {string} outputDir
 */
function formatWithBiome(outputDir) {
  const biomeBin = resolve(REPO_ROOT, 'node_modules/.bin/biome');
  const result = spawnSync(biomeBin, ['format', '--write', outputDir], {
    cwd: REPO_ROOT,
    encoding: 'utf8',
  });
  if (result.error) {
    throw new Error(`biome format failed to run: ${result.error.message}`);
  }
  if (result.status !== 0) {
    throw new Error(`biome format exited with code ${result.status}: ${result.stderr || result.stdout}`);
  }
}

async function main() {
  const outputDir = parseOutputDir(process.argv.slice(2));
  const accentDir = resolve(outputDir, 'accent');
  const grayDir = resolve(outputDir, 'gray');
  await mkdir(accentDir, { recursive: true });
  await mkdir(grayDir, { recursive: true });

  let accentCount = 0;
  for (const hue of HUES) {
    await writeFile(resolve(accentDir, `${hue}.css`), renderAccent(hue), 'utf8');
    accentCount += 1;
  }

  let grayCount = 0;
  for (const grayHue of GRAY_HUES) {
    await writeFile(resolve(grayDir, `${grayHue}.css`), renderGray(grayHue), 'utf8');
    grayCount += 1;
  }

  formatWithBiome(outputDir);

  process.stdout.write(
    `generate-role-maps: wrote ${accentCount} accent/*.css + ${grayCount} gray/*.css to ${outputDir}\n`,
  );
}

main().catch((error) => {
  process.stderr.write(`generate-role-maps: ${error.message}\n`);
  process.exitCode = 1;
});
