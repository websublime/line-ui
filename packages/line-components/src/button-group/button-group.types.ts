/** Axis of `<line-button-group>`: which arrow keys it handles, its ARIA orientation and its flex direction. */
export type ButtonGroupOrientation = 'horizontal' | 'vertical';

/** Where a button sits among the group's items, written as `data-line-button-group-position` on its host. */
export type ButtonGroupPosition = 'first' | 'middle' | 'last' | 'only';
